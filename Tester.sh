echo "Проверка наличия архива в /backup:"
ls -lah /backup 2>/dev/null
echo "Статус выполнения Тест-кейса 4: $?"
echo "----------------------------------------"

echo "=== ТЕСТ-КЕЙС 5: Проверка на ввод букв вместо чисел в пороге N ==="
# Установка высокого порога 99%, чтобы архивация не сработала

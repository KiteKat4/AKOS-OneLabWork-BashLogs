echo "Статус выполнения Тест-кейса 3: $?"
echo "----------------------------------------"

echo "=== ТЕСТ-КЕЙС 4: Проверка на нулевое число в пороге N ==="
# Установка высокого порога 99%, чтобы архивация не сработала

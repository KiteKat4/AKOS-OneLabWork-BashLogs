STATUS=$?

echo "Статус выполнения Тест-кейса 2: $STATUS"
# echo "Проверка содержимого тестовой папки после архивации:"
# ls -lah "$TEST_LOG_DIR"

echo "Проверка наличия архива в /backup:"
